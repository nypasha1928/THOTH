"""Generate a literal Python translation of the supplied Zig Zag state machine.

Only handles the constructs present in reference/support_resistance.pine.
Not a general Pine compiler. Regenerate with python tools/port_indicator.py.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = (root/'reference/support_resistance.pine').read_text()
body = source[source.index('    if bool(HighPivot) and bool(LowPivot)'):source.index('    [ArrayTypeAdv, ArrayValueAdv, ArrayIndexAdv, ArrayTimeAdv]')]
persistent = re.findall(r'    var (?:float|int|string|bool) (\w+) = (\w+)', body)
body = re.sub(r'    var (?:float|int|string|bool) \w+ = \w+\n', '', body)
body = body.replace('ArrayValue.get(ArrayValue.size() - 1)[1]', 'previous_value')
body = body.replace('ArrayType.get(ArrayType.size() - 1)[1]', 'previous_type')
# These are the only conditional expressions inside the selected function.
for val, yes, no, fallback in [('LowValue','HL','LL','L'),('HighValue','HH','LH','H')]:
    pine=f"ArrayType.size() > 2 ? ArrayValue.get(ArrayType.size() - 2) < {val} ? '{yes}' : '{no}' : '{fallback}'"
    py=f"(('{yes}' if ArrayValue.get(ArrayType.size() - 2) < {val} else '{no}') if ArrayType.size() > 2 else '{fallback}')"
    body=body.replace(pine,py)
body=body.replace('previous_value != ArrayValue.get(ArrayValue.size() - 1)', 'bool(previous_value) and previous_value != ArrayValue.get(ArrayValue.size() - 1)')
body=body.replace('else if ', 'elif ').replace(':=', '=').replace('bool(', 'pine_bool(')
body=body.replace('str.substring(', 'substring(').replace('str.length(', 'len(')
for name in ['Type','Value','Index','Time']:
    for suffix in ['', 'Adv']:
        array='Array'+name+suffix
        body=body.replace(array+'.size()', 'len('+array+')')
        body=body.replace(array+'.remove(', array+'.pop(').replace(array+'.push(', array+'.append(')
body=re.sub(r'array\.(remove|push|insert)\((\w+), ', lambda m:m[2]+'.'+{'remove':'pop','push':'append','insert':'insert'}[m[1]]+'(',body)
for name,_ in persistent:
    body=re.sub(r'\b'+name+r'\b', 'self.'+name, body)
body=re.sub(r'\btrue\b','True',body)
body=re.sub(r'\bfalse\b','False',body)
body=re.sub(r'\bna\b','NAN',body)
lines=[]
for line in body.splitlines():
    if not line.strip():continue
    if line.lstrip().startswith(('if ', 'elif ')) or line.strip()=='else':line+=':'
    lines.append('    '+line.rstrip())
header='''# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. https://mozilla.org/MPL/2.0/
# Original Pine Script © TFlab; supplied modifications attributed in reference source.
# Python translation for THOTH. Generated by tools/port_indicator.py.
from math import nan as NAN, isnan


def pine_bool(value):
    return value is not None and not (isinstance(value, float) and isnan(value)) and bool(value)


def substring(value, start):
    return '' if value is None else value[max(0, start):]


class PineArray(list):
    def get(self, index):
        if index < 0 or index >= len(self):
            raise IndexError('Pine array index out of range')
        return self[index]


class ZigZag:
    def __init__(self):
        self.arrays = [PineArray() for _ in range(8)]
        self.previous_value = NAN
        self.previous_type = None
'''
for name,value in persistent:
    value={'na':'NAN','true':'True','false':'False'}.get(value,value)
    header+=f'        self.{name} = {value}\n'
header+='''
    def step(self, high_pivot, low_pivot, high_info, low_info, close):
        ArrayType, ArrayValue, ArrayIndex, ArrayTime, ArrayTypeAdv, ArrayValueAdv, ArrayIndexAdv, ArrayTimeAdv = self.arrays
        HighPivot, LowPivot = high_pivot, low_pivot
        HighValue, HighIndex, HighTime = high_info
        LowValue, LowIndex, LowTime = low_info
        previous_value, previous_type = self.previous_value, self.previous_type
        Correct_HighPivot = Correct_LowPivot = 0.0
        PASS = 0
'''
footer='''
        self.previous_value = ArrayValue[-1] if ArrayValue else NAN
        self.previous_type = ArrayType[-1] if ArrayType else None
        return list(zip(ArrayTypeAdv, ArrayValueAdv, ArrayIndexAdv, ArrayTimeAdv))
'''
result=header+'\n'.join(lines)+'\n'+footer
compile(result,'indicator_core.py','exec')
(root/'thoth/indicator_core.py').write_text(result)
print('Generated literal Zig Zag translation:', len(lines), 'lines')
